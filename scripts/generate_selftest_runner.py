"""Print a Swift runner for existing tests using only the Python standard library.

This Command Line Tools fallback is not an Apple XCTest execution. Compile
TZBoxTestSupport as a module, then compile this output together with every
Tests/TZBoxCoreTests/*.swift source file.
"""
import re
import sys
from pathlib import Path


def discover(root: Path):
    class_pattern = re.compile(r"(?m)^(?:final\s+)?class\s+(\w+)\s*:\s*XCTestCase\s*\{")
    method_pattern = re.compile(
        r"(?m)^[ \t]+func\s+(test\w+)\s*\(\s*\)\s*(async\s*)?(throws\s*)?\{"
    )
    cases = []
    files = sorted((root / "Tests" / "TZBoxCoreTests").glob("*.swift"))
    if not files:
        raise ValueError("No test source files found")
    for source in files:
        text = source.read_text(encoding="utf-8")
        classes = list(class_pattern.finditer(text))
        methods = list(method_pattern.finditer(text))
        declared = re.findall(r"\bfunc\s+(test\w+)\s*\(", text)
        if len(methods) != len(declared):
            raise ValueError(f"Unsupported test declaration in {source}; tests cannot be silently omitted")
        for method in methods:
            owner = next((item for item in reversed(classes) if item.start() < method.start()), None)
            if owner is None:
                raise ValueError(f"Cannot determine XCTestCase for {method.group(1)} in {source}")
            prefix = ("try " if method.group(3) else "") + ("await " if method.group(2) else "")
            cases.append((owner.group(1), method.group(1), prefix))
    identities = [(owner, method) for owner, method, _ in cases]
    if not cases or len(identities) != len(set(identities)):
        raise ValueError("No tests found, or duplicate test method identities")
    return cases


def generate(cases):
    print("""// Generated by scripts/generate_selftest_runner.py. Do not edit.
import Foundation
import TZBoxTestSupport

@main
struct TZBoxSelfTestMain {
    @MainActor
    static func main() async {
        var passed = 0
""")
    for index, (owner, method, prefix) in enumerate(cases):
        print(f"        let test{index} = {owner}()")
        print(f'        if await run("{owner}.{method}", test: test{index}, body: {{')
        print(f"            {prefix}test{index}.{method}()")
        print("        }) { passed += 1 }")
    print(f'        print("Self tests: \\(passed)/{len(cases)} passed; \\(TestRecorder.failureCount) assertion/error failures")')
    print("""        if TestRecorder.failureCount != 0 { exit(1) }
    }

    @MainActor
    static func run(_ name: String, test: XCTestCase, body: () async throws -> Void) async -> Bool {
        let before = TestRecorder.failureCount
        do {
            try test.setUpWithError()
            try await body()
        } catch {
            if TestRecorder.failureCount == before {
                TestRecorder.recordFailure("\\(name) threw: \\(error)")
            }
        }
        do {
            try test.tearDownWithError()
        } catch {
            TestRecorder.recordFailure("\\(name) teardown failed: \\(error)")
        }
        let passed = TestRecorder.failureCount == before
        print("\\(passed ? "PASS" : "FAIL") \\(name)")
        return passed
    }
}
""")


def main():
    root = Path(__file__).resolve().parent.parent
    try:
        cases = discover(root)
    except (OSError, ValueError) as error:
        print(f"Test runner generation failed: {error}", file=sys.stderr)
        return 1
    generate(cases)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
